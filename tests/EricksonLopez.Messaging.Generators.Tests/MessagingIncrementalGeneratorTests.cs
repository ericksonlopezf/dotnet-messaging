    private static string NormalizeLineEndings(string text) =>
        text.Replace("\r\n", "\n").Trim();

    private static (Compilation Compilation, GeneratorDriverRunResult RunResult) RunGenerator(string source)
    {
        var compilation = RoslynTestCompilationFactory.CreateCompilation(source);

        var generator = new MessagingIncrementalGenerator();
        GeneratorDriver driver = CSharpGeneratorDriver.Create(generator);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var outputCompilation, out var diagnostics);

        diagnostics.Should().BeEmpty();
        return (outputCompilation, driver.GetRunResult());
    }

    [Fact]
    public void Generator_DiscoversHandlers_WithCustomMessageTypeAttribute_EmitsExactRegistrations()
    {
        // Arrange
        const string userSource = """
            namespace Sample.Tests;

            using EricksonLopez.Messaging.Attributes;
            using EricksonLopez.Result;

            [MessageType("sample.test-event.v1")]
            public sealed record SampleTestEvent(string Text) : IMessage;

            public sealed class SampleTestEventHandler : IMessageHandler<SampleTestEvent>
            {
                public ValueTask<Result> HandleAsync(
                    SampleTestEvent message,
                    MessageContext context,
                    CancellationToken cancellationToken = default)
                {
                    return ValueTask.FromResult(Result.Success());
                }
            }
            """;

        // Act
        var (_, runResult) = RunGenerator(userSource);

        // Assert
        runResult.GeneratedTrees.Should().ContainSingle();
        var generatedCode = runResult.GeneratedTrees[0].ToString();

        const string expected = """
            // <auto-generated/>
            #nullable enable

            namespace EricksonLopez.Messaging.Generated
            {
                using System.Text.Json.Serialization;

                /// <summary>
                /// Compile-time source-generated JsonSerializerContext for discovered message types.
                /// </summary>
                [JsonSourceGenerationOptions(
                    WriteIndented = false,
                    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
                    PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase,
                    GenerationMode = JsonSourceGenerationMode.Default)]
                [JsonSerializable(typeof(global::Sample.Tests.SampleTestEvent))]
                internal sealed partial class GeneratedMessagingJsonSerializerContext : JsonSerializerContext
                {
                }
            }

            namespace Microsoft.Extensions.DependencyInjection
            {
                using System;
                using EricksonLopez.Messaging.Contracts;

                /// <summary>
                /// Compile-time generated extensions for zero-reflection messaging handler registration.
                /// </summary>
                public static class GeneratedMessagingServiceCollectionExtensions
                {
                    /// <summary>
                    /// Registers all compile-time discovered message handlers and JSON serialization context without runtime reflection.
                    /// </summary>
                    public static IServiceCollection AddGeneratedMessagingHandlers(this IServiceCollection services)
                    {
                        services.AddSingleton<System.Text.Json.Serialization.Metadata.IJsonTypeInfoResolver>(
                            EricksonLopez.Messaging.Generated.GeneratedMessagingJsonSerializerContext.Default);

                        // Handler for message 'sample.test-event.v1'
                        services.AddMessageHandler<global::Sample.Tests.SampleTestEvent, global::Sample.Tests.SampleTestEventHandler>();

                        return services;
                    }
                }
            }
            """;

        NormalizeLineEndings(generatedCode).Should().Be(NormalizeLineEndings(expected));
    }

