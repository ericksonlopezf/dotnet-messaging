    [Fact]
    public void IsCandidateClass_DirectInvocation_ReturnsCorrectResults()
    {
        var tree = CSharpSyntaxTree.ParseText("""
            public abstract class AbstractClass : IDisposable { public void Dispose() {} }
            public class NoBaseListClass { }
            public class ValidClass : IDisposable { public void Dispose() {} }
            public struct StructType { }
            """);
        var root = tree.GetRoot();
        var classes = root.DescendantNodes().OfType<ClassDeclarationSyntax>().ToList();
        var structNode = root.DescendantNodes().OfType<StructDeclarationSyntax>().First();

        var emptyBaseListClass = SyntaxFactory.ClassDeclaration("EmptyBase").WithBaseList(SyntaxFactory.BaseList());

        var method = typeof(MessagingIncrementalGenerator).GetMethod("IsCandidateClass", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!;

        // Abstract class -> false
        ((bool)method.Invoke(null, new object[] { classes[0] })!).Should().BeFalse();
        // No base list -> false
        ((bool)method.Invoke(null, new object[] { classes[1] })!).Should().BeFalse();
        // Base list with 0 types -> false
        ((bool)method.Invoke(null, new object[] { emptyBaseListClass })!).Should().BeFalse();
        // Valid class with base list -> true
        ((bool)method.Invoke(null, new object[] { classes[2] })!).Should().BeTrue();
        // Non-class node -> false
        ((bool)method.Invoke(null, new object[] { structNode })!).Should().BeFalse();
    }

    [Fact]
    public void ResolveMessageTypeName_DirectInvocation_TestsAllAttributeBranches()
    {
        var compilation = RoslynTestCompilationFactory.CreateCompilation("""
            namespace Test;
            using EricksonLopez.Messaging.Attributes;

            [MessageType("custom.bound")]
            public record MsgBound;

            public record MsgNoAttr;

            [AttributeUsage(AttributeTargets.Class)]
            public class OtherAttribute : Attribute { }

            [Other]
            public record MsgOtherAttr;

            [AttributeUsage(AttributeTargets.Class)]
            public class MessageTypeAttribute : Attribute
            {
                public MessageTypeAttribute() {}
                public MessageTypeAttribute(string name) {}
            }

            [MessageType]
            public record MsgEmptyAttr;

            [MessageType()]
            public record MsgEmptyParens;

            [MessageType("syntax.name")]
            public record MsgSyntaxAttr;
            """);

        var msgBound = compilation.GetTypeByMetadataName("Test.MsgBound")!;
        var msgNoAttr = compilation.GetTypeByMetadataName("Test.MsgNoAttr")!;
        var msgOther = compilation.GetTypeByMetadataName("Test.MsgOtherAttr")!;
        var msgEmpty = compilation.GetTypeByMetadataName("Test.MsgEmptyAttr")!;
        var msgEmptyParens = compilation.GetTypeByMetadataName("Test.MsgEmptyParens")!;
        var msgSyntax = compilation.GetTypeByMetadataName("Test.MsgSyntaxAttr")!;

        var method = typeof(MessagingIncrementalGenerator).GetMethod("ResolveMessageTypeName", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!;

        ((string)method.Invoke(null, new object[] { msgBound })!).Should().Be("custom.bound");
        ((string)method.Invoke(null, new object[] { msgNoAttr })!).Should().Be("MsgNoAttr");
        ((string)method.Invoke(null, new object[] { msgOther })!).Should().Be("MsgOtherAttr");
        ((string)method.Invoke(null, new object[] { msgEmpty })!).Should().Be("MsgEmptyAttr");
        ((string)method.Invoke(null, new object[] { msgEmptyParens })!).Should().Be("MsgEmptyParens");
        ((string)method.Invoke(null, new object[] { msgSyntax })!).Should().Be("syntax.name");
    }

    [Fact]
    public void ResolveMessageTypeName_OnMetadataType_TestsConstructorArgumentsPath()
    {
        var metaSource = """
            namespace Lib;
            using EricksonLopez.Messaging.Attributes;

            [MessageType("metadata.bound")]
            public record MetaBound;

            [AttributeUsage(AttributeTargets.Class)]
            public class MessageTypeAttribute : Attribute
            {
                public MessageTypeAttribute() {}
                public MessageTypeAttribute(string name) {}
            }

            [MessageType]
            public record MetaEmpty;
            """;
        var metaComp = RoslynTestCompilationFactory.CreateCompilation(metaSource, "MetaLib");
        using var ms = new System.IO.MemoryStream();
        var emitResult = metaComp.Emit(ms);
        emitResult.Success.Should().BeTrue();
        ms.Seek(0, System.IO.SeekOrigin.Begin);

        var metaRef = MetadataReference.CreateFromStream(ms);
        var consumerComp = CSharpCompilation.Create(
            "Consumer",
            new[] { CSharpSyntaxTree.ParseText("class C {}") },
            new[]
            {
                MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
                MetadataReference.CreateFromFile(typeof(EricksonLopez.Messaging.Attributes.MessageTypeAttribute).Assembly.Location),
                metaRef
            },
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var metaBoundSymbol = consumerComp.GetTypeByMetadataName("Lib.MetaBound")!;
        var metaEmptySymbol = consumerComp.GetTypeByMetadataName("Lib.MetaEmpty")!;

        var method = typeof(MessagingIncrementalGenerator).GetMethod("ResolveMessageTypeName", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!;

        // Tests ConstructorArguments[0].Value -> returns "metadata.bound" directly (ApplicationSyntaxReference is null)
        ((string)method.Invoke(null, new object[] { metaBoundSymbol })!).Should().Be("metadata.bound");

        // Tests ConstructorArguments.Length == 0 on metadata symbol (does not throw IndexOutOfRangeException)
        ((string)method.Invoke(null, new object[] { metaEmptySymbol })!).Should().Be("MetaEmpty");
    }

    [Fact]
    [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Trimming", "IL2075", Justification = "Reflection test")]
    public void GetHandlerInfo_WhenSymbolNotFoundInSemanticModel_ReturnsNull()
    {
        var semanticModel = NSubstitute.Substitute.For<SemanticModel>();
        var classDecl = SyntaxFactory.ClassDeclaration("MyClass");

        var contextCtor = typeof(GeneratorSyntaxContext).GetConstructors(System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance).First();
        var syntaxContext = (GeneratorSyntaxContext)contextCtor.Invoke(new object[] { classDecl, new Lazy<SemanticModel>(() => semanticModel), null! });

        var method = typeof(MessagingIncrementalGenerator).GetMethod("GetHandlerInfo", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!;
        var result = (HandlerDiscoveryInfo?)method.Invoke(null, new object[] { syntaxContext });

        result.Should().BeNull();
    }

