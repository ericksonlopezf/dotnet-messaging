    [Fact]
    public void Generator_WithAbstractClassesAndNonMatchingInterfaces_IgnoresThem()
    {
        // Arrange
        const string userSource = """
            namespace Sample.Tests;

            [MessageType("valid.message")]
            public sealed record ValidMessage(string Data) : IMessage;

            public abstract class AbstractHandler : IMessageHandler<ValidMessage>
            {
                public abstract ValueTask<Result> HandleAsync(ValidMessage message, MessageContext context, CancellationToken cancellationToken);
            }

            public class ClassWithoutBaseTypes
            {
                public void DoSomething() { }
            }

            public class NonGenericInterfaceClass : IDisposable
            {
                public void Dispose() { }
            }

            public class GenericNonHandlerClass : IEquatable<GenericNonHandlerClass>
            {
                public bool Equals(GenericNonHandlerClass? other) => true;
            }

            public struct StructType : IDisposable
            {
                public void Dispose() { }
            }

            public enum SampleEnum { Value1, Value2 }

            public interface ISomeInterface { }
            """;

        // Act
        var (_, runResult) = RunGenerator(userSource);

        // Assert
        runResult.GeneratedTrees.Should().ContainSingle();
        var generatedCode = runResult.GeneratedTrees[0].ToString();
        generatedCode.Should().Contain("AddGeneratedMessagingHandlers");
        generatedCode.Should().NotContain("AbstractHandler");
        generatedCode.Should().NotContain("ClassWithoutBaseTypes");
        generatedCode.Should().NotContain("NonGenericInterfaceClass");
        generatedCode.Should().NotContain("GenericNonHandlerClass");
    }

